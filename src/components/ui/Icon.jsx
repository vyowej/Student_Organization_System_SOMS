export default function Icon({
  name = 'bell',
  size = 16,
  className = '',
  color = 'currentColor',
  strokeWidth = 2,
  style,
  ...props
}) {
  const resolvedName = aliases[name] || name || 'bell'
  const content = iconDefinitions[resolvedName] || iconDefinitions.bell

  if (!content) {
    if (process.env.NODE_ENV !== 'production') {
      console.warn(`[Icon] Unknown icon name: "${name}"`)
    }
    return null
  }

  return (
    <svg
      aria-hidden="true"
      className={`app-icon app-icon-${resolvedName}${className ? ` ${className}` : ''}`}
      fill="none"
      height={size}
      stroke={color}
      strokeLinecap="round"
      strokeLinejoin="round"
      strokeWidth={strokeWidth}
      style={{
        display: 'inline-block',
        verticalAlign: 'middle',
        flexShrink: 0,
        ...style,
      }}
      viewBox="0 0 24 24"
      width={size}
      {...props}
    >
      {content}
    </svg>
  )
}

