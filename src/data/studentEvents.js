export function isEventAlmostFull(event) {
  return event.registeredCount < event.capacity
    && event.registeredCount / event.capacity >= 0.85
}

export function getEventRegistrationState(event, registration) {
  if (registration?.status === 'REGISTERED') return 'REGISTERED'
  if (event.status === 'COMPLETED' || event.status === 'ARCHIVED') return 'EVENT COMPLETED'
  if (event.status !== 'PUBLISHED' || event.registrationStatus === 'CLOSED') return 'REGISTRATION CLOSED'
  if (event.registeredCount >= event.capacity) return 'EVENT FULL'
  return 'NOT REGISTERED'
}
